import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage()
page.on('console', m => { if (m.type()==='error') console.log('CONSOLE ERR:', m.text().slice(0,200)) })
page.on('pageerror', e => console.log('PAGE ERR:', String(e).slice(0,300)))
await page.goto('http://localhost:5211/financials/payouts', { waitUntil: 'commit', timeout: 60000 })
await page.waitForTimeout(6000)
console.log('url:', page.url())
console.log('title:', await page.title())
const txt = await page.evaluate(() => document.body.innerText.slice(0, 700))
console.log('--- body text ---'); console.log(txt)
console.log('--- tables:', await page.locator('table').count(), 'rows:', await page.locator('table tbody tr').count())
await page.screenshot({ path: '.patchtmp/probe.png', fullPage: false })
await browser.close()
