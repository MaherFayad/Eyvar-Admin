/**
 * Turns Recraft vector SVGs into token-coloured React components for the
 * onboarding layer (ONBOARDING-UX-PLAN.md §4.3). Usage:
 *
 *   node scripts/illustrations/tokenise.mjs <source-dir> <out-dir>
 *
 * Every `<key>.svg` in the source dir becomes `<out-dir>/<Key>Art.tsx`. The
 * C2PA metadata is dropped, the full-canvas background rect is dropped, the
 * viewBox is cropped to the drawing with 4% padding (measured in Chromium),
 * and every `fill="rgb(...)"` becomes one of the Tailwind fill utilities
 * below. A solid fill outside the palette snaps to the nearest token and is
 * reported; a gradient or any element other than a path fails that file.
 */
import { chromium } from 'playwright'
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'

const [src, out] = process.argv.slice(2)
if (!src || !out) throw new Error('usage: tokenise.mjs <source-dir> <out-dir>')
mkdirSync(out, { recursive: true })

const FILLS = {
  'rgb(12,105,68)': 'fill-primary',
  'rgb(23,26,33)': 'fill-foreground',
  'rgb(231,240,236)': 'fill-brand-lt',
  'rgb(255,255,255)': 'fill-background',
  'rgb(246,248,249)': 'fill-muted',
  'rgb(107,114,128)': 'fill-muted-foreground',
}

function nearestFill(fill, file) {
  const flat = fill.replace(/\s/g, '')
  if (FILLS[flat]) return FILLS[flat]
  const m = flat.match(/^rgb\((\d+),(\d+),(\d+)\)$/)
  if (!m) throw new Error(`fill ${fill} is outside the palette`)
  const [r, g, b] = m.slice(1).map(Number)
  let best = null
  for (const [key, cls] of Object.entries(FILLS)) {
    const [kr, kg, kb] = key.match(/\d+/g).map(Number)
    const d = (r - kr) ** 2 + (g - kg) ** 2 + (b - kb) ** 2
    if (best === null || d < best.d) best = { d, cls }
  }
  console.warn(`${file}: ${fill} snapped to ${best.cls}`)
  return best.cls
}

const pascal = (key) =>
  key
    .split(/[.\-_]/)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('')

async function convert(page, file) {
  const key = basename(file, '.svg')
  const svg = readFileSync(join(src, file), 'utf8').replace(/<metadata>[\s\S]*?<\/metadata>/, '')
  const vb = svg.match(/viewBox="([^"]+)"/)?.[1]
  if (!vb) throw new Error('no viewBox')
  const [, , vw, vh] = vb.split(' ').map(Number)
  const kept = []
  for (const [, attrs] of svg.matchAll(/<path\b([^>]*)\/>/g)) {
    const fill = attrs.match(/fill="([^"]+)"/)?.[1]
    const d = attrs.match(/\bd="([^"]+)"/)?.[1]
    const transform = attrs.match(/transform="([^"]+)"/)?.[1]
    if (!fill || !d) throw new Error('path without fill or d')
    if (new RegExp(`^M 0 0 L ${vw} 0 L ${vw} ${vh} L 0 ${vh} L 0 0 z$`).test(d.trim())) continue
    const cls = nearestFill(fill, file)
    kept.push({ cls, d, transform: transform && transform !== 'translate(0,0)' ? transform : null })
  }
  const other = svg.match(/<(?!path\b|svg\b|\/svg)[a-zA-Z]+/g)
  if (other) throw new Error(`unexpected elements: ${[...new Set(other)].join(' ')}`)
  const inner = kept
    .map((p) => `<path d="${p.d}"${p.transform ? ` transform="${p.transform}"` : ''}/>`)
    .join('')
  await page.setContent(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${vw}" height="${vh}">${inner}</svg>`,
  )
  const box = await page.evaluate(() => {
    const b = document.querySelector('svg').getBBox()
    return { x: b.x, y: b.y, w: b.width, h: b.height }
  })
  const pad = Math.max(box.w, box.h) * 0.04
  const viewBox = [box.x - pad, box.y - pad, box.w + 2 * pad, box.h + 2 * pad]
    .map((n) => Math.round(n))
    .join(' ')
  const name = `${pascal(key)}Art`
  const body = kept
    .map(
      (p) =>
        `      <path className="${p.cls}"${p.transform ? ` transform="${p.transform}"` : ''} d="${p.d}" />`,
    )
    .join('\n')
  const tsx = `/* Generated by scripts/illustrations/tokenise.mjs from ${file}. Do not hand-edit. */
import type { ArtProps } from './types'

export function ${name}({ className }: ArtProps) {
  return (
    <svg
      viewBox="${viewBox}"
      className={className}
      data-illustration="${key}"
      aria-hidden="true"
      focusable="false"
    >
${body}
    </svg>
  )
}
`
  writeFileSync(join(out, `${name}.tsx`), tsx)
  return { key, name, bytes: tsx.length, paths: kept.length }
}

const browser = await chromium.launch()
const page = await browser.newPage()
const failures = []
for (const file of readdirSync(src).filter((f) => f.endsWith('.svg')).sort()) {
  try {
    const m = await convert(page, file)
    console.log(
      `${m.key.padEnd(22)} ${m.name.padEnd(26)} ${String(m.paths).padStart(3)} paths ${String(m.bytes).padStart(6)} B`,
    )
  } catch (error) {
    failures.push(`${file}: ${error.message}`)
  }
}
await browser.close()
for (const f of failures) console.error('FAILED', f)
if (failures.length > 0) process.exitCode = 1
