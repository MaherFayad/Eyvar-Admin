import { chromium } from 'playwright'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 } })
const page = await ctx.newPage()
page.on('console', (m) => console.log('BROWSER:', m.text()))
await page.goto('http://localhost:4327/management/reports/pages/DSH-1', { waitUntil: 'networkidle' })
await page.waitForTimeout(500)
await page.getByRole('button', { name: 'Edit' }).click()
await page.waitForTimeout(400)
const id = await page.evaluate(() => document.querySelector('[data-block-id]')?.getAttribute('data-block-id'))
console.log('id=', id)
await page.evaluate((bid) => document.querySelector(`[data-block-id="${bid}"]`)?.focus(), id)
const active1 = await page.evaluate(() => document.activeElement?.getAttribute('data-block-id'))
console.log('active before press:', active1)
await page.keyboard.press('Shift+F10')
await page.waitForTimeout(300)
const menuCount = await page.locator('[role="menu"]').count()
console.log('menu count:', menuCount)
const btn = await page.evaluate((bid) => {
  const frame = document.querySelector(`[data-block-id="${bid}"]`)
  const b = frame?.querySelector('button[aria-label^="More actions for"]')
  return b ? b.getAttribute('aria-label') : null
}, id)
console.log('found kebab button:', btn)
await browser.close()
