import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', e => console.log('ERR', String(e).slice(0,300)))
await page.goto('http://localhost:4327/management/reports/RPT-1', { waitUntil: 'load' })
await page.waitForTimeout(1800)
await page.getByRole('combobox', { name: 'Compare to' }).click()
await page.waitForTimeout(300)
const options = await page.locator('[role="option"]').allTextContents()
console.log('options', options)
await page.getByRole('option', { name: /Fixed range/ }).click()
await page.waitForTimeout(500)
console.log('popover heading visible?', await page.getByText('Fixed comparison range').count())
await page.screenshot({ path: 'scripts/harness/shots/_probe-fixed.png', fullPage: true })
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
await page.getByRole('combobox', { name: 'Compare to' }).click()
await page.getByRole('option', { name: /^Previous period/ }).click()
await page.waitForTimeout(500)
console.log('show as toggle?', await page.getByRole('combobox', { name: 'Show as' }).count())
await page.screenshot({ path: 'scripts/harness/shots/_probe-showas.png', fullPage: true })
await browser.close()
