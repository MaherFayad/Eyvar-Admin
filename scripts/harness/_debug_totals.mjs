import { chromium } from 'playwright'
const BASE = 'http://localhost:4327'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } })
const page = await ctx.newPage()
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE ERROR', m.text()) })
await page.goto(`${BASE}/management/reports`, { waitUntil: 'load' })
await page.waitForTimeout(1000)
await page.getByRole('link', { name: 'New report' }).click().catch(() => page.getByRole('button', { name: 'New report' }).click())
await page.waitForTimeout(1000)
await page.getByLabel('Measure', { exact: true }).click()
await page.getByRole('option').first().click()
await page.waitForTimeout(500)
await page.getByLabel('Chart type', { exact: true }).click()
await page.waitForTimeout(300)
await page.getByRole('option', { name: 'Data table' }).click()
await page.waitForTimeout(500)
const columnsGroup = page.getByRole('group', { name: 'Columns' })
await columnsGroup.getByRole('checkbox').first().click()
await page.waitForTimeout(700)

const totalsCb = page.getByLabel(/otals/)
console.log('totals checkbox count', await totalsCb.count())
console.log('checked before', await totalsCb.isChecked().catch((e) => String(e)))
await totalsCb.click()
await page.waitForTimeout(700)
console.log('checked after', await totalsCb.isChecked().catch((e) => String(e)))
console.log('tfoot count', await page.locator('tfoot').count())
console.log('tfoot tr count', await page.locator('tfoot tr').count())
await page.screenshot({ path: './scripts/harness/shots/debug-totals.png' })
await browser.close()
