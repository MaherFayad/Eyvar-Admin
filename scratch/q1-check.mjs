import { chromium } from 'playwright'
const b=await chromium.launch(); const p=await b.newPage({viewport:{width:1440,height:900}})
await p.goto('http://localhost:5244/operations/people',{waitUntil:'networkidle'}); await p.waitForTimeout(900)
const sy=await p.evaluate(()=>{const s=[...document.querySelectorAll('main div')].find(d=>d.scrollHeight>d.clientHeight+4);if(s)s.scrollTop=300;return s?s.scrollTop:-1})
await p.getByRole('button',{name:'Account'}).click(); await p.waitForTimeout(400)
await p.getByRole('menuitemradio',{name:'Arabic'}).click()
await p.waitForFunction(()=>document.documentElement.dir==='rtl',null,{timeout:5000})
await p.keyboard.press('Escape'); await p.waitForTimeout(300)
const st=(l)=>p.evaluate(()=>document.documentElement.dir+'/'+document.documentElement.lang).then(v=>console.log(l.padEnd(34),v))
await st('after switch')
