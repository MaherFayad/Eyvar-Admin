console.log('url unchanged'.padEnd(34), p.url())
// a REAL in-app route change: click a sub-tab link
await p.getByRole('link',{name:/Live Dispatch/}).click(); await p.waitForTimeout(900)
await st('after in-app nav (SPA)')
console.log('url now'.padEnd(34), p.url())
await p.reload({waitUntil:'networkidle'}); await p.waitForTimeout(700)
await st('after RELOAD  <- Q1/AC-33 gap')
