import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 1100 } })
await p.goto('http://localhost:5199/entity/DRV-0201?view=identity', { waitUntil: 'networkidle' })
await p.waitForTimeout(2000)
const dl = p.locator('dl').first()
await dl.screenshot({ path: 'scratch/identity-after.png' })
console.log('grid text:', (await dl.innerText()).replace(/\n/g, ' | '))
console.log('grid box :', await dl.boundingBox())
await b.close()
