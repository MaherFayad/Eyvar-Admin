/** The feed panel in Arabic, with a row selected: bar, reserve and action all mirror. */
import { chromium } from 'playwright'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })
const page = await ctx.newPage()
await page.goto('http://localhost:4325/operations/dispatch', { waitUntil: 'networkidle' })
await page.waitForTimeout(800)
await page.locator('header button').last().click()
await page.getByRole('menuitemradio', { name: 'Arabic' }).click()
await page.waitForTimeout(2000)
await page.getByRole('button', { name: /^SREQ-001/ }).click()
await page.waitForTimeout(400)
await page.locator('div.rounded-xl.border.bg-card.shadow-2').first()
  .screenshot({ path: './scratch/shots-board/dispatch.panel-ar.png' })
console.log('done')
await browser.close()
