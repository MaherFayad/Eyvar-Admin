import { chromium } from 'playwright'
const BASE = 'http://localhost:4327'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1344, height: 1000 } })
const page = await ctx.newPage()
await page.goto(BASE + '/management/reports/dashboards/DSH-1', { waitUntil: 'networkidle' })
await page.waitForTimeout(2000)
await page.screenshot({ path: 'scratch/shots-dash/dsh1-1344.png' })
await page.getByRole('button', { name: 'Board range' }).click()
await page.waitForTimeout(1200)
await page.screenshot({ path: 'scratch/shots-dash/range-popover.png' })
await page.keyboard.press('Escape')
await page.waitForTimeout(400)
await page.getByRole('button', { name: 'Add filter' }).click()
await page.waitForTimeout(600)
await page.screenshot({ path: 'scratch/shots-dash/filter-popover.png' })
await browser.close()
console.log('ok')
