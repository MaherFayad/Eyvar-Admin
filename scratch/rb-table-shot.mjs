import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1600, height: 1200 } })
await page.goto('http://localhost:4325/management/reports/RPT-2', { waitUntil: 'networkidle' })
await page.waitForTimeout(4000)
const t = page.locator('table').first()
await t.scrollIntoViewIfNeeded()
await t.screenshot({ path: './scratch/shots-partial/table.en.png' })
console.log('headers:', await page.evaluate(() => [...document.querySelectorAll('thead th')].map((th) => th.innerText.replace(/\n/g, ' | '))))
console.log('last cells:', await page.evaluate(() => [...document.querySelectorAll('tbody tr')].map((r) => r.lastElementChild.innerText.replace(/\n/g, ' | '))))
await browser.close()
