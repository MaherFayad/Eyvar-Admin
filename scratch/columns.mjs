import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2 })
await p.goto('http://localhost:5199/operations/people', { waitUntil: 'networkidle' })
await p.waitForTimeout(2500)
await p.getByRole('button', { name: 'Choose columns' }).click()
await p.waitForTimeout(400)
await p.screenshot({ path: './scratch/shots/people-columns-1280.png' })
await p.keyboard.press('Escape')
await p.getByRole('button', { name: 'Filter', exact: true }).click()
await p.waitForTimeout(400)
await p.screenshot({ path: './scratch/shots/people-filter-1280.png' })
await p.close()
await b.close()
console.log('done')
