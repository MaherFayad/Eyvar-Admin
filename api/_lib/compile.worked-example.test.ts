/**
 * One-off generator for `docs/09-analytics-v2/examples/compile-quick-rides-by-city.sql`
 * (WP-6.4's brief) — captures the exact parameterised SQL `compile.ts` emits
 * for a real fixture measure and writes it to that file. Not a regression
 * test: it exists to be run once (`npx vitest run api/_lib/compile.worked-example.test.ts`)
 * whenever the compiler's query shape changes, so the worked example never
 * drifts from what the compiler actually produces. Deleted from the suite
 * after generating the doc — see WP-6.4's final report.
 */
import { describe, expect, it } from 'vitest'
import { writeFile, readFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createTestDatabase } from '../_test/db'
import type { Database } from './db'
import { fetchMeasureRows } from './compile'
import { measureFixtures } from '@/data/fixtures/measures'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '../..')
const EXAMPLES_DIR = path.join(ROOT, 'docs', '09-analytics-v2', 'examples')

describe('worked example generator', () => {
  it('captures the SQL for trips.completed, quick rides only, grouped by pickup', async () => {
    const { pglite, db } = await createTestDatabase()
    try {
      const measuresSql = await readFile(path.join(EXAMPLES_DIR, 'measures.seed.sql'), 'utf8')
      const tripsSql = await readFile(path.join(EXAMPLES_DIR, 'trips.seed.sql'), 'utf8')
      await pglite.exec(measuresSql)
      await pglite.exec(tripsSql)

      const captured: { text: string; params: unknown[] }[] = []
      const capturingDb: Database = {
        sql: async (strings, ...values) => {
          let text = strings[0] ?? ''
          for (let i = 0; i < values.length; i++) text += `$${i + 1}${strings[i + 1] ?? ''}`
          captured.push({ text, params: values })
          return db.sql(strings, ...values)
        },
        close: db.close,
      }

      const measure = measureFixtures.find((m) => m.key === 'trips.completed')!
      const result = await fetchMeasureRows(capturingDb, measure, 'count', {
        filters: [...measure.population.predicate, { field: 'trip.kind', op: 'eq', value: 'Quick' }],
        groupBy: ['trip.pickup'],
        subjectAllow: null,
      })

      expect(result.rows.rows.length).toBeGreaterThanOrEqual(0)

      const mainQuery = captured.find((c) => c.text.trim().startsWith('SELECT') && c.text.includes('FROM "fixture_trips"'))
      expect(mainQuery).toBeTruthy()

      const doc = `-- Generated by WP-6.4's worked-example test (api/_lib/compile.worked-example.test.ts)
-- from \`fetchMeasureRows\` against \`trips.completed\` — the catalogue's own
-- population predicate ("trip.status" = 'done') plus a \`trip.kind = 'Quick'\`
-- filter, grouped by \`trip.pickup\` — the closest real question the fixtures
-- answer to "quick rides by city" (05-backend.md §6 names this file; no
-- catalogue measure both reads \`quickRides\` *and* carries a groupable
-- dimension — \`trips.quickRides\` is a \`daily-snapshots\` measure and that
-- resource has none, per its own \`dimensions: []\`). \`compile.ts\`'s header
-- explains why this is the whole compiler for a trend leg: the row fetch
-- below, plus \`resolveTrendLeg\` (src/data/reporting/resolve/core.ts) run
-- unchanged over what it returns.
--
-- Population (from \`measures\` / \`measure_sources\`, 0003_catalogue.sql + 0005_runs.sql):
--   resource        trips -> fixture_trips
--   predicate       "trip.status" = 'done'  (the catalogue's own; R5-15)
--   query filter    "trip.kind" = 'Quick'   (this leg's own, appended)
--   time field      endedAt (Riyadh-local day; \`localDay: true\` in field_columns_json)
--   group by        trip.pickup (one level; no second dimension requested)
--
-- The parameters below are never string-interpolated into the SQL text —
-- \`compile.ts\`'s \`SqlBuilder\` binds them positionally exactly as a literal
-- tagged template would.

${mainQuery!.text};

-- Bound parameters, in order:
${mainQuery!.params.map((p, i) => `--   $${i + 1} = ${JSON.stringify(p)}`).join('\n')}
`
      await writeFile(path.join(EXAMPLES_DIR, 'compile-quick-rides-by-city.sql'), doc)
    } finally {
      await pglite.close()
    }
  })
})
