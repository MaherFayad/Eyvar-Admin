/**
 * Field - restyled for Eyvar. This is shadcn 4's replacement for `form`.
 *
 * NOTE FOR THE INVENTORY: spec §5.2 item 14 asks for `form`. In shadcn 4.19 the
 * `form` registry item is an EMPTY ALIAS - it ships no files and no
 * `react-hook-form` binding; `field` superseded it. `form` was requested and
 * resolved to this. No form library is installed, so validation wiring is an open
 * request to utilities-engineer (see the 0.4 handoff).
 *
 * Rules applied
 *   §4.4/§10.4 VALIDATION IS THREE LAYERS AND ALL THREE ARE REQUIRED.
 *              (1) Inline field error - 1px `--ev-red` border AND `--ev-red-lt`
 *                  fill AND a 12px `--ev-red` message with a leading filled
 *                  circle-exclamation glyph, INSERTED below the field, replacing
 *                  nothing. Never colour alone. The label above keeps its normal
 *                  colour.
 *              (2) ONE page-level critical banner, the first element of the
 *                  content block, stating the COUNT and listing each blocking
 *                  item. A PALE TINTED CARD (R1/R16), not a saturated red strip.
 *              (3) Disabled-until-valid: `Save` greyed, `Discard` always enabled
 *                  (AC-52).
 *   §10.2      label ABOVE the field, 13px/400; helper text BELOW the control,
 *              12px `--ev-text-2`. CONSTRAINTS AND CONSEQUENCES LIVE IN HELPER
 *              TEXT, NEVER IN A TOOLTIP (§5.7).
 *   §10.2      a CHECKBOX's helper text indents to the checkbox's LABEL, not to
 *              its box.
 *   §10.1      one concern per card; short related fields sit 50/50 on one row,
 *              long and free-text fields go full width.
 *   §8.2.1     A DERIVED VALUE IS NOT A FIELD. It has no box, no border and no
 *              fill; it is not focusable, not in the tab order, carries
 *              `aria-readonly="true"` and `aria-live="polite"`, and it must never
 *              be rendered with the disabled treatment. Use `DerivedValue` (V-03).
 *   AC-75      every interpolation is a named placeholder inside a single key.
 *              No concatenation.
 */
