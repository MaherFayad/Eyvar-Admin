/**
 * Seeded disputes and lost-property reports — legacy `DB.disputes` (`:14391`)
 * and `DB.lostFound` (`:14448`), widened to the depth the screen needs.
 *
 * ## Why there are 28 and 27 rather than 3 and 3
 *
 * The screen literal held three of each. Three rows cannot exercise a second
 * page, cannot populate a facet, and cannot show an operator what the table
 * looks like when it is full — which is the state it is in every day. Both
 * collections therefore page at least twice at the default 25.
 *
 * ## Every status the screen filters by has at least one row
 *
 * A facet that can never match anything is an invisible hole, and it is the
 * most common defect in this repo. The counts below are asserted in
 * `clients/disputes.test.ts` rather than only written here, because a comment
 * stating a count is a comment that goes stale.
 *
 * | field | values, and how many rows carry each |
 * |---|---|
 * | `status` | `open` 12 · `under-review` 7 · `resolved` 9 |
 * | `resolution.outcome` | `full-refund` 3 · `partial-refund` 2 · `goodwill-credit` 2 · `declined` 2 |
 * | `kind` | all six, minimum three rows each |
 * | `claimantType` | `rider` 23 · `captain` 5 |
 * | `LostFoundItem.status` | `searching` 10 · `with-captain` 9 · `returned` 8 |
 *
 * ## Every seeded resolution carries `refundId: null`, and that is not laziness
 *
 * The refund store holds three rows, `REF-0001`–`REF-0003`
 * (`fixtures/financials.ts:64`), none of which belongs to a dispute, and
 * `clients/revenue.ts:53` seeds its sequence from that length — so the next
 * refund this app mints is `REF-0004`. Writing `REF-0007` onto a seeded
 * resolution would name a row that does not exist **and** collide with the
 * fourth refund anyone issues. That is the exact defect `issueRefund`'s own
 * header records: a green assertion on the name of a posting nothing wrote.
 *
 * So a seeded resolution records the verdict and the amount and says plainly
 * that its refund is not on file. **A resolution performed in this session
 * carries a real `refundId`**, because `resolveDispute` calls `issueRefund` and
 * that call writes a real refund, a real credit note and a real posting.
 *
 * ## The edge cases seeded on purpose
 *
 * - **`DSP-118` has `dueAt: null`** — a claim with no clock. `lib/sla.ts` rule 1:
 *   that is a value, it renders `No clock`, and it sorts last.
 * - **`DSP-104` and `DSP-111` are past their deadline** and still open, so the
 *   breached reading is reachable without editing a fixture.
 * - **`DSP-109` has `againstId: null`** — a duplicate toll charged by the
 *   platform's own billing, which no captain caused.
 * - **`DSP-116` is owned by `USR-3`, not the acting operator**, so the
 *   *"somebody else is on this"* reading is reachable.
 * - **`LF-208` has `driverId: null`** — a rider who cannot identify the trip.
 *   The *"ask the captain"* step is genuinely impossible, which is the §11.2
 *   disabled-with-a-reason case the screen has to render.
 * - **`DSP-113` carries a claimant whose name is 62 characters**, because a
 *   column that has never met a long Arabic name has never been laid out.
 *
 * ## Names and ids agree with the collections they reference
 *
 * Every `claimantId`, `againstId`, `tripId` and `subscriptionId` resolves in
 * `riders.ts`, `drivers.ts`, `trips.ts` or `subscriptions.ts`, and every name
 * matches that collection's own. The screen literal did not: it called
 * `RDR-1041` *"Sarah Al-Ghamdi"* where `riders.ts:22` calls her *"Nora
 * Al-Harbi"*, and `DRV-0104` *"Sultan Al-Harbi"* where `drivers.ts:177` calls
 * him *"Hassan Al-Ghamdi"*. That is `REMEDIATION-PLAN.md` §4.6 item 4, and it
 * is not repeated here.
 */

